// Checks Layer 2 (Hansen distance, solvent comparison, mixtures) and Layer 3 (sphere fitting from good/poor data).
import { compareSolvents, hansenDistance, mixtureHSP, SOLVENTS } from '../src/hansen';
import { fitSphere } from '../src/sphere';

let bad = 0;
const check = (ok: boolean, what: string, detail = '') => {
  if (ok) console.log('ok  ', what);
  else { bad++; console.error('FAIL', what, detail); }
};
const near = (a: number, b: number, tol = 0.01) => Math.abs(a - b) <= tol;
const solvent = (name: string) => SOLVENTS.find((s) => s.name === name)!;

// Layer 2: distance, ranking.
check(near(hansenDistance({ d: 18, p: 1.4, h: 2 }, { d: 15.5, p: 10.4, h: 7 }), Math.sqrt(4 * 6.25 + 81 + 25)), 'Ra toluene–acetone');
check(hansenDistance({ d: 1, p: 2, h: 3 }, { d: 1, p: 2, h: 3 }) === 0, 'Ra of identical parameters is 0');
const ranked = compareSolvents(solvent('Toluene').hsp, SOLVENTS);
check(ranked[0].solvent.name === 'Toluene' && ranked[0].red === undefined, 'ranking puts the solvent itself first, and gives no RED without R₀');
check(compareSolvents(solvent('Toluene').hsp, SOLVENTS, 8).every((c) => near(c.red!, c.ra / 8, 1e-9)), 'RED = Ra / R₀ when R₀ is given');

// Mixtures: volume-fraction averaging, and conversion from mole and mass fractions.
const etoh = solvent('Ethanol'), water = solvent('Water');
const vol = mixtureHSP([{ ...etoh, amount: 50 }, { ...water, amount: 50 }], 'volume');
check(vol.ok && near(vol.value.hsp.d, 15.65) && near(vol.value.hsp.p, 12.4) && near(vol.value.hsp.h, 30.85), '50/50 v/v ethanol/water');
const mole = mixtureHSP([{ ...etoh, amount: 1 }, { ...water, amount: 1 }], 'mole');
const phiE = 58.5 / (58.5 + 18.0);
check(mole.ok && near(mole.value.phi[0], phiE, 1e-9) && near(mole.value.hsp.h, phiE * 19.4 + (1 - phiE) * 42.3) && near(mole.value.v!, (58.5 + 18) / 2, 1e-9), 'equimolar ethanol/water converts to volume fractions with molar volumes');
const mass = mixtureHSP([{ ...etoh, amount: 1 }, { ...water, amount: 1 }], 'mass');
const ve = 58.5 / 46.07, vw = 18.0 / 18.02;
check(mass.ok && near(mass.value.phi[0], ve / (ve + vw), 1e-9), '50/50 w/w ethanol/water converts through densities M/V');
check(!mixtureHSP([{ name: 'X', hsp: { d: 1, p: 1, h: 1 }, amount: 1 }, { ...water, amount: 1 }], 'mole').ok, 'mole basis refuses a component without molar volume');
check(!mixtureHSP([{ ...water, amount: 1 }], 'volume').ok, 'one component is not a mixture');

// Layer 3: recover a known sphere from good/poor scores generated by it.
// Polystyrene sphere from Hansen (2007), Table A.2: δD 21.3, δP 5.8, δH 4.3, R₀ 12.7.
const truth = { d: 21.3, p: 5.8, h: 4.3 }, r0 = 12.7;
const tested = SOLVENTS.map((s) => ({ name: s.name, hsp: s.hsp, good: hansenDistance(truth, s.hsp) < r0 }));
const fit = fitSphere(tested);
check(fit.ok && fit.value.fit === 1 && fit.value.rows.every((r) => !r.misfit), `sphere fit reproduces every score (${tested.filter((t) => t.good).length} good, ${tested.filter((t) => !t.good).length} poor)`, JSON.stringify(fit));
if (fit.ok) {
  const v = fit.value;
  console.log(`      fitted centre ${v.centre.d.toFixed(2)} / ${v.centre.p.toFixed(2)} / ${v.centre.h.toFixed(2)}, R₀ ${v.r0.toFixed(2)} (truth 21.3 / 5.8 / 4.3, 12.7)`);
  check(v.r0 <= r0 + 0.05, 'smallest consistent sphere is no larger than the true one');
  const prediction = SOLVENTS.every((s) => (hansenDistance(v.centre, s.hsp) / v.r0 < 1) === (hansenDistance(truth, s.hsp) < r0));
  check(prediction, 'RED from the fitted sphere predicts the same solvents as the true sphere');
}
// A contradictory point lowers DATAFIT below 1 and is flagged.
const noisy = tested.map((t) => (t.name === 'n-Hexane' ? { ...t, good: true } : t));
const nf = fitSphere(noisy);
check(nf.ok && nf.value.fit < 1 && nf.value.warnings.some((w) => w.includes('wrong side')), 'a contradictory result lowers DATAFIT and is reported');
check(!fitSphere(tested.filter((t) => t.good)).ok, 'no poor solvents: refused');
check(!fitSphere(tested.filter((t) => !t.good)).ok, 'no good solvents: refused');

console.log(`${bad} failures`);
process.exit(bad ? 1 : 0);
