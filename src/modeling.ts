// 3D structures and file formats for molecular modelling programs (Avogadro, Chem3D, PyMOL, VMD, GaussView…).
// OpenChemLib builds a conformer with explicit hydrogens and relaxes it with the MMFF94s+ force field.
// Polymer * ends are capped with hydrogen so the repeat unit is a closed, valence-correct molecule.
import { ConformerGenerator, ForceFieldMMFF94, Molecule } from 'openchemlib';
import { Doc } from './model';
import { toOCL, toSmiles } from './chem';

type Mol = InstanceType<typeof Molecule>;

export interface Model3D {
  mol: Mol;
  capped: number; // number of * ends replaced by H
  energy?: number; // MMFF94s+ total energy after minimisation, kcal/mol
  minimised: boolean;
  smiles: string;
}

/** Build one low-energy 3D conformer (requires OpenChemLib resources to be registered). */
export function build3D(doc: Doc, seed = 1): Model3D {
  const real = doc.atoms.filter((a) => a.el !== '*');
  if (!real.length) throw new Error('Nothing to export');
  const { mol } = toOCL(doc);
  let capped = 0;
  for (let i = 0; i < mol.getAllAtoms(); i++) {
    if (mol.getAtomicNo(i) === 0) { mol.setAtomicNo(i, 1); capped++; }
  }
  mol.ensureHelperArrays(Molecule.cHelperParities);
  const smiles = toSmiles(doc);
  const conf = new ConformerGenerator(seed).getOneConformerAsMolecule(mol);
  if (!conf) throw new Error('Could not build a 3D conformer for this structure');
  const out: Model3D = { mol: conf, capped, minimised: false, smiles };
  try {
    const ff = new ForceFieldMMFF94(conf, ForceFieldMMFF94.MMFF94SPLUS, {});
    out.minimised = ff.minimise() === 0;
    out.energy = ff.getTotalEnergy();
  } catch { /* MMFF94 has no parameters for some elements: keep the generated conformer */ }
  conf.setName(conf.getName() || 'MolCanvas structure');
  return out;
}

const title = (m: Model3D) => m.smiles || 'MolCanvas structure';

/** MDL molfile with 3D coordinates and explicit hydrogens. */
export function molfile3D(m: Model3D, v3000 = false): string {
  m.mol.setName(title(m));
  return v3000 ? m.mol.toMolfileV3() : m.mol.toMolfile();
}

export function sdf3D(m: Model3D): string {
  const mf = m.mol.getMolecularFormula();
  const fields: [string, string][] = [
    ['SMILES', m.smiles],
    ['FORMULA', mf.formula],
    ['MW', mf.relativeWeight.toFixed(3)],
  ];
  if (m.energy !== undefined) fields.push(['MMFF94S_PLUS_ENERGY_KCAL_MOL', m.energy.toFixed(4)]);
  if (m.capped) fields.push(['NOTE', `${m.capped} polymer * end(s) capped with H`]);
  const data = fields.map(([k, v]) => `> <${k}>\n${v}\n`).join('\n');
  return `${molfile3D(m).replace(/\s*$/, '\n')}${data}\n$$$$\n`;
}

export function xyz(m: Model3D): string {
  const mol = m.mol;
  const n = mol.getAllAtoms();
  const lines = [String(n), title(m)];
  for (let i = 0; i < n; i++) {
    lines.push(`${Molecule.cAtomLabel[mol.getAtomicNo(i)].padEnd(2)} ${f(X(mol, i), 10, 5)} ${f(Y(mol, i), 10, 5)} ${f(Z(mol, i), 10, 5)}`);
  }
  return `${lines.join('\n')}\n`;
}

/** PDB with HETATM records (residue UNL) and CONECT records. */
export function pdb(m: Model3D): string {
  const mol = m.mol;
  const n = mol.getAllAtoms();
  const perEl = new Map<string, number>();
  const lines = [`COMPND    ${title(m).slice(0, 70)}`, 'AUTHOR    GENERATED BY MOLCANVAS'];
  for (let i = 0; i < n; i++) {
    const el = Molecule.cAtomLabel[mol.getAtomicNo(i)].toUpperCase();
    const k = (perEl.get(el) ?? 0) + 1;
    perEl.set(el, k);
    let name = `${el}${k}`;
    name = el.length === 1 && name.length < 4 ? ` ${name}`.padEnd(4) : name.slice(0, 4).padEnd(4);
    const q = mol.getAtomCharge(i);
    const chg = q ? `${Math.abs(q)}${q > 0 ? '+' : '-'}` : '  ';
    lines.push(
      `HETATM${String(i + 1).padStart(5)} ${name} UNL A   1    ${f(X(mol, i), 8, 3)}${f(Y(mol, i), 8, 3)}${f(Z(mol, i), 8, 3)}  1.00  0.00          ${el.padStart(2)}${chg}`,
    );
  }
  mol.ensureHelperArrays(Molecule.cHelperNeighbours);
  for (let i = 0; i < n; i++) {
    const nb: number[] = [];
    // Double and triple bonds are written as repeated CONECT partners (Open Babel / RDKit convention).
    for (let j = 0; j < mol.getAllConnAtoms(i); j++) {
      for (let o = 0; o < mol.getConnBondOrder(i, j); o++) nb.push(mol.getConnAtom(i, j) + 1);
    }
    for (let s = 0; s < nb.length; s += 4) {
      lines.push(`CONECT${String(i + 1).padStart(5)}${nb.slice(s, s + 4).map((x) => String(x).padStart(5)).join('')}`);
    }
  }
  lines.push('END');
  return `${lines.join('\n')}\n`;
}

/** Tripos MOL2 with SYBYL atom types and bond types (no partial charges). */
export function mol2(m: Model3D): string {
  const mol = m.mol;
  mol.ensureHelperArrays(Molecule.cHelperRings);
  const n = mol.getAllAtoms();
  const nb = mol.getAllBonds();
  const types: string[] = [];
  for (let i = 0; i < n; i++) types.push(sybylType(mol, i));
  const lines = ['@<TRIPOS>MOLECULE', title(m), `${n} ${nb} 1 0 0`, 'SMALL', 'NO_CHARGES', '', '@<TRIPOS>ATOM'];
  const perEl = new Map<string, number>();
  for (let i = 0; i < n; i++) {
    const el = Molecule.cAtomLabel[mol.getAtomicNo(i)];
    const k = (perEl.get(el) ?? 0) + 1;
    perEl.set(el, k);
    lines.push(`${String(i + 1).padStart(7)} ${`${el}${k}`.padEnd(6)} ${f(X(mol, i), 10, 4)} ${f(Y(mol, i), 10, 4)} ${f(Z(mol, i), 10, 4)} ${types[i].padEnd(6)} 1 UNL1    0.0000`);
  }
  lines.push('@<TRIPOS>BOND');
  for (let b = 0; b < nb; b++) {
    const a1 = mol.getBondAtom(0, b), a2 = mol.getBondAtom(1, b);
    let t = String(mol.getBondOrder(b));
    if (mol.isAromaticBond(b)) t = 'ar';
    else if (isAmideBond(mol, a1, a2) || isAmideBond(mol, a2, a1)) t = 'am';
    lines.push(`${String(b + 1).padStart(6)} ${String(a1 + 1).padStart(5)} ${String(a2 + 1).padStart(5)} ${t}`);
  }
  lines.push('@<TRIPOS>SUBSTRUCTURE', '     1 UNL1        1 TEMP              0 ****  ****    0 ROOT');
  return `${lines.join('\n')}\n`;
}

// OCL keeps y (and z) pointing the other way; its molfile writer negates both, so do the same here
// to keep every format in the same frame (a 180° rotation about x, chirality is unchanged).
const X = (mol: Mol, i: number) => mol.getAtomX(i);
const Y = (mol: Mol, i: number) => -mol.getAtomY(i);
const Z = (mol: Mol, i: number) => -mol.getAtomZ(i);

function f(x: number, w: number, d: number): string {
  return x.toFixed(d).padStart(w);
}

function neighbours(mol: Mol, i: number): { j: number; order: number }[] {
  const out = [];
  for (let k = 0; k < mol.getAllConnAtoms(i); k++) out.push({ j: mol.getConnAtom(i, k), order: mol.getConnBondOrder(i, k) });
  return out;
}

const isCarbonylC = (mol: Mol, c: number) =>
  mol.getAtomicNo(c) === 6 && neighbours(mol, c).some((e) => e.order === 2 && (mol.getAtomicNo(e.j) === 8 || mol.getAtomicNo(e.j) === 16));

// C(=O)–N single bond
function isAmideBond(mol: Mol, c: number, nAtom: number): boolean {
  return mol.getAtomicNo(nAtom) === 7 && !mol.isAromaticAtom(nAtom) && isCarbonylC(mol, c) &&
    neighbours(mol, c).some((e) => e.j === nAtom && e.order === 1);
}

function sybylType(mol: Mol, i: number): string {
  const z = mol.getAtomicNo(i);
  const el = Molecule.cAtomLabel[z];
  const nb = neighbours(mol, i);
  const maxOrder = Math.max(0, ...nb.map((e) => e.order));
  const doubles = nb.filter((e) => e.order === 2).length;
  const arom = mol.isAromaticAtom(i);
  const q = mol.getAtomCharge(i);
  switch (z) {
    case 1: return 'H';
    case 6:
      if (arom) return 'C.ar';
      if (maxOrder === 3 || doubles === 2) return 'C.1';
      if (doubles === 1) return 'C.2';
      if (q === 1 && nb.length === 3) return 'C.cat';
      return 'C.3';
    case 7: {
      if (q === 1 && nb.length === 4 && maxOrder === 1) return 'N.4';
      if (arom) return 'N.ar';
      if (maxOrder === 3 || doubles === 2) return 'N.1';
      if (nb.some((e) => e.order === 1 && isCarbonylC(mol, e.j))) return 'N.am';
      if (doubles === 1) return q === 1 ? 'N.pl3' : 'N.2';
      // planar N: bonded to an aromatic or sp2 atom (anilines, enamines)
      if (nb.some((e) => mol.isAromaticAtom(e.j) || neighbours(mol, e.j).some((x) => x.order === 2))) return 'N.pl3';
      return 'N.3';
    }
    case 8: {
      // carboxylate / phosphate / sulfonate-type terminal oxygens sharing a negative charge
      if (nb.length === 1) {
        const c = nb[0].j;
        const terminalO = neighbours(mol, c).filter((e) => mol.getAtomicNo(e.j) === 8 && mol.getAllConnAtoms(e.j) === 1);
        const anionic = terminalO.some((e) => mol.getAtomCharge(e.j) === -1);
        if (anionic && terminalO.length >= 2 && [6, 15, 16].includes(mol.getAtomicNo(c)) && mol.getAtomCharge(c) === 0) return 'O.co2';
      }
      if (doubles === 1) return 'O.2';
      if (nb.length === 1 && mol.getAtomicNo(nb[0].j) === 7 && mol.getAtomCharge(nb[0].j) === 1) return 'O.2'; // nitro, N-oxide
      return 'O.3';
    }
    case 15: return 'P.3';
    case 16: {
      const oDouble = nb.filter((e) => e.order === 2 && mol.getAtomicNo(e.j) === 8).length;
      if (oDouble >= 2) return 'S.O2';
      if (oDouble === 1) return 'S.O';
      if (doubles === 1 && nb.length === 1) return 'S.2';
      return 'S.3';
    }
    default:
      return el;
  }
}
