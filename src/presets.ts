// Preset library. SMILES strings are parsed and laid out at runtime by OpenChemLib.
// kind 'group': the leading '*' is the attachment point (click an atom to attach).
// kind 'polymer': '*' atoms are the ends of the repeat unit and are drawn as brackets.

export type PresetKind = 'molecule' | 'group' | 'polymer';

export interface Preset {
  name: string;
  smiles: string;
  cat: string;
  kind: PresetKind;
  aka?: string; // extra search terms / abbreviations
}

const P = (cat: string, kind: PresetKind, rows: [string, string, string?][]): Preset[] =>
  rows.map(([name, smiles, aka]) => ({ name, smiles, cat, kind, aka }));

